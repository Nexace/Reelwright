// tools/component_assets.mjs — install a HyperFrames catalog component WITH its assets (E2: the 9 asset-bearing components).
//   componentPlan(name, { textures, allTextures }) → { item, html, assets: [{ target, from? , gen?, note }], missing: [{ file, why }] }
//   installComponent(name, proj, opts)             → writes <proj>/hf/blocks/<name>.html and each asset at <proj>/hf/<target>
//   assetBearing()                                 → names of the vendored components that list more than one file
// Where an asset comes from (nothing is downloaded):
//   a font that is in this repo's fonts/ (OFL, licence text copied beside it)      Caveat 700 → the five hw-* components
//   a texture PNG → generated by tools/texture_gen.mjs (a STAND-IN luminance map under the same file name; the upstream ambientCG
//                   photos are not in the repo). caption-texture: its six; texture-mask-text: the 9 base masks, or --all-textures
//   anything else (Geist, Permanent Marker, Courier Prime) is `missing` unless you point `fontDir` (CLI --font-dir) at a folder that
//                   holds the file under its upstream name (you check the licence); otherwise it is `missing` with the reason, and the component is not installed: a
//   component without its font would silently render in a fallback, which is worse than a refusal.
// Root-absolute asset URLs in a component ("/assets/…") are rewritten relative to the page so pvk and file:// pages find them.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { texturePng, textureKind } from "./texture_gen.mjs";

const ROOT = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const COMPONENTS = path.join(ROOT, "vendor", "hyperframes", "registry", "components");
const LOCAL_FONTS = { "Caveat-700-latin.woff2": { from: "fonts/caveat/700.woff2", licence: "fonts/caveat/OFL.txt", licenceAs: "Caveat-OFL.txt" } };
const NEEDS_DOWNLOAD = {
  "Geist-Latin.woff2": "Geist (SIL OFL) is not in fonts/ and cannot be fetched at build time",
  "Geist-OFL.txt": "the licence text of the Geist font, which is not in fonts/",
  "permanent-marker-400.woff2": "Permanent Marker (Apache-2.0) is not in fonts/ and cannot be fetched at build time",
  "courier-prime-700.woff2": "Courier Prime (SIL OFL) is not in fonts/ and cannot be fetched at build time",
};
const BASE_MASKS = ["lava", "rock", "concrete", "brick", "wood", "onyx", "carpet", "metal", "snow"];   // texture-mask-text's named presets

export const assetBearing = () => fs.readdirSync(COMPONENTS).filter((n) => {
  const f = path.join(COMPONENTS, n, "registry-item.json");
  return fs.existsSync(f) && (JSON.parse(fs.readFileSync(f, "utf8")).files || []).length > 1;
}).sort();

export function componentPlan(name, { textures, allTextures = false, fontDir } = {}) {
  const dir = path.join(COMPONENTS, name), rj = path.join(dir, "registry-item.json");
  if (!/^[\w-]+$/.test(name) || !fs.existsSync(rj)) throw new Error(`no component ${name}`);
  const item = JSON.parse(fs.readFileSync(rj, "utf8"));
  const [main, ...rest] = item.files || [];
  if (!main || !main.path.endsWith(".html")) throw new Error(`${name}: first file is not html`);
  const assets = [], missing = [], want = textures ? new Set(textures) : null;
  for (const f of rest) {
    const base = path.posix.basename(f.path), stem = base.replace(/\.[^.]+$/, "");
    const target = path.posix.normalize(f.target);
    if (target.startsWith("..") || path.isAbsolute(target)) throw new Error(`${name}: asset target ${f.target} leaves the project`);
    if (LOCAL_FONTS[base]) {
      const L = LOCAL_FONTS[base];
      assets.push({ target, from: path.join(ROOT, L.from), note: `${L.from} (SIL OFL, same family, latin subset)` });
      assets.push({ target: path.posix.join(path.posix.dirname(target), L.licenceAs), from: path.join(ROOT, L.licence), note: "licence text" });
    } else if (fontDir && NEEDS_DOWNLOAD[base] && fs.existsSync(path.join(fontDir, base))) {
      assets.push({ target, from: path.join(fontDir, base), note: `${base} from --font-dir (you supplied it: check its licence)` });
    } else if (NEEDS_DOWNLOAD[base]) missing.push({ file: base, why: NEEDS_DOWNLOAD[base] });
    else if (/\.png$/i.test(base)) {
      const base0 = name === "texture-mask-text" && !allTextures && !want && !BASE_MASKS.includes(stem);
      if (base0 || (want && !want.has(stem))) continue;
      assets.push({ target, gen: stem, note: `procedural ${textureKind(stem)} stand-in for the ambientCG ${stem} map (tools/texture_gen.mjs)` });
    } else missing.push({ file: base, why: "no local source for this asset type" });
  }
  return { item, main: path.join(dir, main.path), assets, missing };
}

export function installComponent(name, proj, opts = {}) {
  const plan = componentPlan(name, opts);
  if (plan.missing.length) return { ok: false, ...plan };
  const hf = path.join(proj, "hf");
  const out = [];
  for (const a of plan.assets) {
    const dest = path.join(hf, a.target);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    if (a.gen) fs.writeFileSync(dest, texturePng(a.gen)); else fs.copyFileSync(a.from, dest);
    out.push(path.relative(proj, dest));
  }
  const dest = path.join(hf, "blocks", name + ".html");
  fs.mkdirSync(path.dirname(dest), { recursive: true });
  const html = fs.readFileSync(plan.main, "utf8").replace(/url\((["'])\/assets\//g, "url($1assets/");   // root-absolute → page-relative
  const stand = plan.assets.some((a) => a.gen);
  fs.writeFileSync(dest, `<!-- ${name} from the HyperFrames catalog (heygen-com/hyperframes, Apache-2.0, see vendor/hyperframes/LICENSE and VENDORED.md). ` +
    `Drive it from render(t) via KIT.block("${name}"). Its assets are in hf/${[...new Set(plan.assets.map((a) => path.posix.dirname(a.target).split("/").slice(0, 2).join("/")))].join(", hf/")}` +
    `${stand ? "; the textures are procedural stand-ins, not the upstream photographs" : ""}. -->\n` + html);
  return { ok: true, ...plan, dest, assets: out };
}
