// Build-time syntax highlighting for KIT.math.code (tools/manim-grid.js): source text -> the token data a film loads.
// Uses the vendored, trimmed shiki (vendor/shiki/, MIT; JS regex engine, 7 languages, 2 themes). Runs in Node only, never in the page;
// deterministic (same code, language, theme -> same JSON). No network.
//   highlight(code, { lang, theme = 'github-dark', tabSize = 4 }) -> { lang, theme, bg, fg, lines: [[{ content, color, fontStyle }]] }
//   langOf(file)   language from the extension (js ts py json sh bash html css), or undefined
//   dataScript(id, data, kind = 'CODE') -> the JS a film loads: window.CODE["id"] = {...};  (kind 'MODEL' stores an OBJ text string)
import path from "node:path";
import { highlight as shiki, LANGS, THEMES } from "../../vendor/shiki/shiki.min.mjs";

export { LANGS, THEMES };
const EXT = { ".js": "javascript", ".mjs": "javascript", ".cjs": "javascript", ".jsx": "javascript", ".ts": "typescript", ".tsx": "typescript", ".py": "python",
  ".json": "json", ".sh": "bash", ".bash": "bash", ".zsh": "bash", ".html": "html", ".htm": "html", ".css": "css" };
export const langOf = (file) => EXT[path.extname(file).toLowerCase()];

export function highlight(code, { lang, theme = "github-dark", tabSize = 4 } = {}) {
  if (!lang) throw new Error(`highlight: give a language (${LANGS.join(", ")})`);
  const text = String(code).replace(/\r\n?/g, "\n").replace(/\t/g, " ".repeat(tabSize)).replace(/\n+$/, "");
  const r = shiki(text, lang, theme);
  return { lang, theme, bg: r.bg, fg: r.fg, lines: r.lines };
}

export function dataScript(id, data, kind = "CODE") {
  if (!/^[\w-]+$/.test(id)) throw new Error(`id "${id}": letters, digits, _ and - only`);
  return `// generated by reelwright code (tools/manim/code.mjs) - do not edit\nwindow.${kind}=window.${kind}||{};window.${kind}[${JSON.stringify(id)}]=${JSON.stringify(data)};\n`;
}
