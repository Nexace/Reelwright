// Writes <page dir>/theme.css (film/ for pvk, hf/ for hyperframes) from the project's style and brand.json.
// The film's index.html links it right after kit.css: <link rel="stylesheet" href="theme.css">.
//   style: themes/<name>.css (project.json "style", or REELWRIGHT_STYLE from `reelwright ... --style <name>`)
//   brand.json: { "colors": { "<token>": "#hex" }, "fonts": { "display" | "text" | "mono": "<bundled family>" |
//                 { "family", "src": "<file in the project>", "weight" } }, "logo": "<file in the project>", "tone": "..." }
//   (tone is for the writer; it does not change the render). Brand wins over the theme.
// Every bundled family (fonts/<slug>/) named in a --kit-font-* token gets @font-face rules. The font files are inlined
// as data: URLs, which Chromium loads before any script runs: film code that measures text at load (offsetWidth)
// then measures the real face, in every renderer and in preview, as the HyperFrames producer's own inlining does.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(fileURLToPath(new URL("..", import.meta.url)));
const FONTS = path.join(ROOT, "fonts"), THEMES = path.join(ROOT, "themes");
const slug = (f) => f.toLowerCase().replace(/\s+/g, "-");
const posix = (p) => p.split(path.sep).join("/");
const FALLBACK = { display: "sans-serif", text: "sans-serif", mono: "monospace" };
const FONT_TYPES = { ".woff2": "font/woff2", ".woff": "font/woff", ".ttf": "font/ttf", ".otf": "font/otf" };
const inline = (f) => `data:${FONT_TYPES[path.extname(f).toLowerCase()] || "application/octet-stream"};base64,${fs.readFileSync(f).toString("base64")}`;

export const themes = () => fs.readdirSync(THEMES).filter((f) => f.endsWith(".css")).map((f) => f.slice(0, -4)).sort();

export function writeTheme(DIR, P) {
  const hf = P.renderer === "hyperframes";
  const page = path.join(DIR, hf ? "hf" : "film");
  const style = process.env.REELWRIGHT_STYLE || P.style;
  const bf = path.join(DIR, "brand.json");
  const brand = fs.existsSync(bf) ? JSON.parse(fs.readFileSync(bf, "utf8")) : null;
  const out = path.join(page, "theme.css");
  if (!style && !brand) { fs.writeFileSync(out, "/* no style or brand.json: kit.css defaults */\n"); return; }
  if (!fs.readFileSync(path.join(page, "index.html"), "utf8").includes("theme.css")) {
    console.error(`${posix(path.relative(ROOT, page))}/index.html needs <link rel="stylesheet" href="theme.css"> after kit.css`);
    process.exit(1);
  }

  // a file the page loads (the logo; fonts are inlined): relative to the page for pvk; copied under hf/kit/ for hyperframes
  const kitDir = path.join(page, "kit");
  const url = (abs, sub) => {
    if (!hf) return posix(path.relative(page, abs));
    const dest = path.join(kitDir, sub);
    fs.mkdirSync(path.dirname(dest), { recursive: true });
    fs.copyFileSync(abs, dest);
    return posix(path.relative(page, dest));
  };

  let css = "/* generated by tools/theme.mjs — edit themes/*.css or brand.json instead */\n";
  if (style) {
    const f = path.join(THEMES, style + ".css");
    if (!/^[\w-]+$/.test(style) || !fs.existsSync(f)) { console.error(`unknown style "${style}"; have: ${themes().join(", ")}`); process.exit(1); }
    css += `#stage { background-color: var(--kit-bg); background-image: var(--kit-bg-image); color: var(--kit-ink);
  font-family: var(--kit-font-text); }\n` + fs.readFileSync(f, "utf8");
  }
  if (brand) {
    const v = Object.entries(brand.colors || {}).map(([k, c]) => `--kit-${k.replace(/^--(kit-)?/, "")}: ${c};`);
    for (const [role, font] of Object.entries(brand.fonts || {})) {
      const fam = typeof font === "string" ? font : font.family;
      if (typeof font === "object") {
        const src = path.resolve(DIR, font.src);
        if (!fs.existsSync(src)) { console.error(`brand.json font not found: ${font.src}`); process.exit(1); }
        css += `@font-face { font-family: "${fam}"; font-weight: ${font.weight || 400}; font-display: block; ` +
          `src: url("${inline(src)}"); }\n`;
      }
      v.push(`--kit-font-${role}: "${fam}", ${FALLBACK[role] || "sans-serif"};`);
    }
    if (brand.logo) v.push(`--kit-logo: url("${url(path.resolve(DIR, brand.logo), path.join("brand", path.basename(brand.logo)))}");`);
    css += `/* brand.json */\n:root { ${v.join(" ")} }\n`;
  }

  // @font-face for every bundled family a font token names
  const fams = new Set();
  for (const m of css.matchAll(/--kit-font-[\w-]+\s*:([^;]+);/g)) for (const q of m[1].matchAll(/"([^"]+)"/g)) fams.add(q[1]);
  let faces = "";
  for (const fam of fams) {
    const d = path.join(FONTS, slug(fam));
    if (!fs.existsSync(d)) continue;   // a system or brand-file family
    for (const w of fs.readdirSync(d).filter((f) => f.endsWith(".woff2")).sort())
      faces += `@font-face { font-family: "${fam}"; font-weight: ${w.slice(0, -6)}; font-display: block; ` +
        `src: url("${inline(path.join(d, w))}") format("woff2"); }\n`;
  }
  fs.writeFileSync(out, faces + css);
}
